#!/bin/bash
# Build ravynOS /bin/sh: a statically linked, dyld-free Mach-O built from the
# FreeBSD ash sources in this directory.
#
# Why a script and not the Makefile
# --------------------------------
# Makefile goes through bsd.prog.mk and links `-ledit`; BSD/lib/libedit takes a
# Darwin-host branch that produces a 0-byte stub, and libedit is not built. It
# also expects a crt1.o that the ravynOS SDK does not ship. This script links
# the same SRCS list with the shape that tools/bootlab/build_init.sh already
# proves on the target: `-nostdlib -nostdlibinc -static -e _start` against the
# ravynOS Libsystem archives, with our own entry point (ravynos_port.c).
#
# Two outputs are produced:
#   $OBJDIR/sh          the ravynOS static binary (the deliverable)
#   $HOSTDIR/sh         the same sources linked for the Darwin host, used to
#                       actually RUN the shell in tests -- see build-ravynos.sh
#                       --host-only. Excludes ravynos_port.c, which is the
#                       platform glue the host libc already provides.
#
# Usage:
#   ./build-ravynos.sh              # build the ravynOS static binary
#   ./build-ravynos.sh --host-only  # build the runnable host verification binary
set -euo pipefail

R=$(cd "$(dirname "$0")/../../.." && pwd)
S=$R/BSD/bin/sh
SDK=${RAVYN_SDKROOT:-$HOME/Projects/build/Developer/Platforms/ravynOS.platform/Developer/SDKs/ravynOS.sdk}
L=$R/Libraries/Libsystem
OBJDIR=${OBJDIR:-/tmp/ravyn-sh-build}
HOSTDIR=${HOSTDIR:-/tmp/ravyn-sh-build-host}
# libedit's two build outputs. LEDIR is the include path the shell's
# myhistedit.h needs (histedit.h, filecomplete.h); it was simply absent
# before, which is the other half of why -DNO_HISTORY was in force.
#   LEOBJ  archive compiled against the ravynOS SDK, for the target link
#   LEHOST archive compiled for the Darwin host, for running the shell here
LEOBJ=${LEOBJ:-/tmp/ravyn-libedit-build}
LEHOST=${LEHOST:-/tmp/ravyn-libedit-host}
LEDIR=$R/BSD/lib/libedit/src
# bmake, and the bmake include tree. These are the same values the task
# specifies; the wrappers (isysroot-cc for -isysroot, macar for ar) are the
# ones build-libraries.sh exports, and libedit's Makefile reads CC/AR/LD
# from the environment, so they are passed through rather than re-guessed.
BMAKE=${BMAKE:-/usr/local/bin/bmake}
GENDIR=$OBJDIR/gen
# The static link itself is delegated to tools/bootlab/link-static.sh, which
# owns the archive list, the -nodefaultlibs dance that keeps clang's implicit
# -lSystem from resolving to the SDK's placeholder libSystem.B.dylib, the
# residue stubs (Libraries/Libsystem/static/stubs.c) and the
# -DVARIANT_STATIC pthread archive (libsystem_pthread/static). Nothing here
# depends on a scratch directory: the recipe is entirely in the repo.
LINK_STATIC=${LINK_STATIC:-$R/tools/bootlab/link-static.sh}
STATIC_START=${STATIC_START:-$R/tools/bootlab/static-start.c}

unset DEVELOPER_DIR || true
# Invoke through xcrun rather than `xcrun -f clang`: xcrun exports SDKROOT and
# the toolchain env that make the host's own <stdio.h> resolvable. A bare
# /Library/.../clang path compiles the ravynOS sources fine (they only need
# -isysroot) but cannot find the host SDK headers for the generators.
XCRUN=${XCRUN:-xcrun}
HOST_CC=${HOST_CC:-$XCRUN clang}
TARGET_CC=${TARGET_CC:-$XCRUN clang}

# Must match Makefile:4-31.
SRCS="bltin/echo.c alias.c arith_yacc.c arith_yylex.c cd.c error.c eval.c \
exec.c expand.c histedit.c input.c jobs.c mail.c main.c memalloc.c \
miscbltin.c mystring.c options.c output.c parser.c redir.c show.c trap.c \
var.c builtins.c nodes.c syntax.c shims.c"

# Feature switches:
#   -DSHELL       required. bltin/bltin.h keys off it: without it the #else
#                 branch runs `#undef main`, which destroys bltin/echo.c's
#                 `#define main echocmd` and the `echo` builtin disappears.
#                 With it, the bltin/* builtins write through the shell's output
#                 buffers (putchar/fprintf -> out1c/outfmt), which is what makes
#                 `echo > file` redirect correctly.
#   -DNO_VFORK    defined in shell.h; see the comment there. The kernel has no
#                 vfork(), so the vforkexecshell() optimisation is compiled out.
#   -D__unused=   the ravynOS headers mark parameters __unused.
#
# -DNO_HISTORY is GONE. It was here because libedit was not built, and
# libedit was not built because BSD/lib/libedit/Makefile took a Darwin-host
# branch that touched a 0-byte stub. That branch now builds (the six
# BUILT_SOURCES headers it needs are generated by src/makelist), so the
# shell's line editing and history are compiled in and linked against the
# real libedit.a. The other 7 guards on NO_HISTORY (eval.c, input.c,
# main.c, options.c, parser.c, trap.c, var.c) are all upstream's own and
# all key on the same switch, so removing it turns on the whole feature
# coherently: el_gets() in input.c, HISTSIZE/TERM as settable variables,
# histsave() on exit, and displayhist for `fc`.
#
# PTRATTR is GONE too, and that is Task 2 of the line-editing work. The
# -D__sized_by(x)= family was papering over a gap in the SDK's sys/cdefs.h,
# which lacked the ABI-neutral pointer-attribute macros that the SDK's own
# sys/socket.h:561,565 and sys/sysctl.h:795-799 use unconditionally. The
# macros are now defined in the header itself, at SDK generation time, by
# CDEFS_TAIL in tools/bootlab/build-libraries.sh. Keep this list free of
# them: a command-line -D does not reach a consumer outside this script and
# hides the header being wrong.
COMMON_CFLAGS="-D__unused= -DSHELL -DNO_VFORK \
 -Wno-nullability-completeness -Wno-implicit-int \
 -Wno-implicit-function-declaration -Wno-int-conversion -Wno-unused \
 -Wno-parentheses -Wno-format -Wno-sign-compare -Wno-deprecated-non-prototype"

# --------------------------------------------------------------------------
# Generated sources. parser.c and token.h's parser are pre-generated in the
# tree, but nodes.c/syntax.c/token.h are built by mknodes/mksyntax/mktokens.
# --------------------------------------------------------------------------
gen_sources() {
	mkdir -p "$GENDIR"
	if [ ! -f "$GENDIR/syntax.c" ] || [ "$S/mksyntax.c" -nt "$GENDIR/syntax.c" ]; then
		# -include the fbsdcompat shim and -D__unused= are what Makefile:61-69
		# prescribes for the host-side generators.
		$HOST_CC -include"$L/libsystem_c/fbsdcompat/_fbsd_compat_.h" \
			"-D__unused=" -o "$GENDIR/mksyntax" "$S/mksyntax.c"
		(cd "$GENDIR" && ./mksyntax)
	fi
	if [ ! -f "$GENDIR/nodes.c" ] || [ "$S/mknodes.c" -nt "$GENDIR/nodes.c" ]; then
		$HOST_CC -include"$L/libsystem_c/fbsdcompat/_fbsd_compat_.h" \
			"-D__unused=" -o "$GENDIR/mknodes" "$S/mknodes.c"
		(cd "$GENDIR" && ./mknodes "$S/nodetypes" "$S/nodes.c.pat")
	fi
	if [ ! -f "$GENDIR/token.h" ] || [ "$S/mktokens" -nt "$GENDIR/token.h" ]; then
		(cd "$GENDIR" && "$S/mktokens")
	fi
	# builtins.c/builtins.h are generated from builtins.def by mkbuiltins.
	# The copies in the tree were stale -- they still listed test/[/printf/kill,
	# which builtins.def has commented out -- so the shell bound those names to
	# the empty bodies in shims.c. `test 1 -lt 2` then reported failure and
	# every `while`/`if` loop was dead. Regenerate so the table and builtins.def
	# agree.
	if [ "$S/builtins.def" -nt "$S/builtins.c" ]; then
		(cd "$S" && ./mkbuiltins .)
	fi
}

src_for() { # nodes.c and syntax.c are generated; everything else is in the tree
	case "$(basename "$1")" in
	nodes.c|syntax.c) echo "$GENDIR/$(basename "$1")" ;;
	*) echo "$S/$1" ;;
	esac
}

# --------------------------------------------------------------------------
# libedit. The shell's line editing is libedit, and libedit is a real
# library now: BSD/lib/libedit/Makefile builds it instead of touching a
# 0-byte stub. Two archives come out of the same sources:
#
#   $LEHOST/libedit.a   compiled for the Darwin host, so the shell can
#                       actually be RUN here. Linked with the host's termcap
#                       (tgetent/tputs/tgoto, which libedit's terminal.c
#                       calls unconditionally) via the system libncurses.
#   $LEOBJ/libedit.a     compiled against the ravynOS SDK by the bmake
#                       recipe, for the target link.
#
# Both are produced by BSD/lib/libedit/Makefile, which is the one place that
# knows how to build this library. The flags are not re-derived here.
#
# The six headers the recipe needs (vi.h emacs.h common.h fcns.h help.h
# func.h) are GENERATED by src/makelist from the command tables in
# vi.c/emacs.c/common.c -- see src/Makefile.am:7-23. They are not in the
# tree, and their absence is the entire reason the old Darwin branch
# touched a stub: 12 of the 32 sources include "common.h" or "fcns.h"
# unconditionally, so the archive could not be assembled at all.
# --------------------------------------------------------------------------
build_libedit() {
	build_libedit_host
}

# RESOLVED -- termcap is what used to block the target archive, and it no
# longer does.
#
# libedit src/terminal.c calls tgetent/tgetflag/tgetnum/tgetstr/tgoto/tputs
# unconditionally from terminal_set(); it has no non-termcap path. ravynOS had
# no termcap at all: no <termcap.h>/<curses.h>/<ncurses.h> in the SDK, no tget*
# in any Libsystem archive, and no termcap database in the SDK tree.
# BSD/lib/ncurses is present in source but its Darwin branch is a stub, and the
# prebuilt lib/libncursestw.a committed beside it is a THIN archive whose
# member objects are absent, so it cannot be linked either.
#
# The answer is Libraries/Libsystem/libsystem_termcap: an original 4-clause
# BSD termcap with the six entry points and a small built-in entry table.
# It is NOT a stub. It declines to describe a terminal it cannot verify
# rather than emitting escape sequences the target was never told it
# understands, which is what the "deliberately NOT stubbed" note below used
# to be worried about.
#
# Two things this script must therefore do, and both are load-bearing:
#
#   1. Build the static archive (or at least have it present). Done by
#      `bmake -m BSD/share/mk all` in that component's static/ subdir; see
#      build_termcap_static below, which does it here so the target build is
#      reproducible from this script alone.
#
#   2. Make <termcap.h> reachable when libedit compiles. libedit's own
#      src/sys.h includes config.h into every translation unit, and config.h
#      has HAVE_TERMCAP_H 1 (src/terminal.c:57). So terminal.c includes
#      <termcap.h> and the header has to exist in the ravynOS SDK, which is
#      what the component's Makefile installs. It also declares the six
#      prototypes: terminal.c declares them itself only under
#      `#if defined(__sun)' (src/terminal.c:71-78), so without the header the
#      ravynOS build would take an IMPLICIT `int tgetstr()' and truncate the
#      returned pointer to 32 bits on x86_64. That is not a warning; it is a
#      wrong library. config.h also had HAVE_CURSES_H/HAVE_NCURSES_H 1 from
#      being generated on a host that had curses, which is why the same
#      translation unit failed on 'curses.h: file not found'; both are now
#      correctly undefined.
#
# libedit's six headers (vi.h emacs.h common.h fcns.h func.h help.h) are
# GENERATED by src/makelist, not vendored. src/Makefile.am:2 lists them under
# BUILT_SOURCES. Both builds need them; the generation is factored out so the
# target build cannot drift from the host build again.
gen_libedit_headers() {
	local out=$1 d="$R/BSD/lib/libedit/src"
	rm -rf "$out"; mkdir -p "$out"
	( cd "$d" || exit 1
	  for h in vi emacs common; do
		AWK=awk sh ./makelist -h "$h.c" > "$out/$h.h" || exit 1
	  done
	  AWK=awk sh ./makelist -fh "$out/vi.h" "$out/emacs.h" \
		"$out/common.h" > "$out/fcns.h" || exit 1
	  AWK=awk sh ./makelist -fc "$out/vi.h" "$out/emacs.h" \
		"$out/common.h" > "$out/func.h" || exit 1
	  AWK=awk sh ./makelist -bh vi.c emacs.c common.c \
		> "$out/help.h" || exit 1
	) || { echo "libedit header generation FAILED" >&2; exit 1; }
}

build_libedit_target() {
	[ -s "$LEOBJ/libedit.a" ] && { echo "==> libedit (target): up to date"; return 0; }
	echo "==> libedit (ravynOS SDK archive)"
	mkdir -p "$LEOBJ"
	# libedit's own six generated headers, into the TARGET object dir. The
	# host path did this already (see gen_libedit_headers); the target path
	# did not, so src/chared.c could not find "common.h" and bmake stopped
	# on the first object. The headers are generated, not vendored, so the
	# target build needs them generated exactly as the host build does.
	gen_libedit_headers "$LEOBJ/gen"
	# The same environment tools/bootlab/build-libraries.sh exports for every
	# bmake sub-make. These are not re-guesses: CC is the isysroot-cc wrapper
	# (Apple clang's cc shim ignores a custom SDK passed via --sysroot for
	# #include resolution, so it has to become -isysroot), AR is the macar
	# wrapper (macOS ar rejects the -D that bmake passes), and LD is the bare
	# name `ld' because clang's --ld-path= rejects a path. DEVELOPER_DIR stays
	# unset so the host xcrun shims keep working.
	#
	# MAKEOBJDIR is how this makefile tree is told where to build, and
	# getting it wrong is the whole reason this function previously produced
	# nothing usable. BSD/share/mk/bsd.obj.mk:78 is an unconditional
	# `.OBJDIR: ${.CURDIR}'; the only things that override it are
	# MAKEOBJDIRPREFIX and MAKEOBJDIR (bsd.obj.mk:79-83), both documented
	# there as ENVIRONMENT variables. Passing OBJDIR= on the bmake command
	# line does NOT work -- .OBJDIR is already assigned by then, and a `:='
	# is not a `?='.
	#
	# With .OBJDIR left at the source directory, every object AND the
	# archive landed in BSD/lib/libedit/, and the check below then printed
	#   libedit.a is 0 bytes -- that is the old stub defect
	# about a file that was never there at all. A diagnostic that names a
	# file which does not exist is worse than no diagnostic.
	#
	# Building out of tree also stops the build writing 32 object files and
	# a 350 KB archive into the source tree, where a later link could pick
	# up a stale one.
	(
		cd "$R/BSD/lib/libedit" || exit 1
		MAKEOBJDIR="$LEOBJ" \
		RAVYN_SDKROOT="$SDK" SYSROOT_DIR="$SDK" \
		ROOT_SOURCE_DIR="$R" \
		CpuArch=x86_64 MACOS_VERSION_MIN="${MACOS_VERSION_MIN:-15.0}" \
		CC="$R/tools/bootlab/isysroot-cc" \
		AR="$R/tools/bootlab/macar" \
		LD=ld \
		EXTRA_DEFINES="-DXNU_PLATFORM_MacOSX" \
		"$BMAKE" -m "$R/BSD/share/mk" \
		CFLAGS="--sysroot=$SDK -mmacos-version-min=${MACOS_VERSION_MIN:-15.0} \
			-I$R/BSD/lib/libedit/src -I$R/BSD/lib/libedit \
			-I$LEOBJ -I$LEOBJ/gen" \
		libedit.a
	) || { echo "libedit target build FAILED" >&2; exit 1; }
	[ -d "$R/BSD/lib/libedit" ] && ls "$R/BSD/lib/libedit"/*.o >/dev/null 2>&1 && {
		echo "libedit objects landed in the source tree; MAKEOBJDIR did not take" >&2
		exit 1; }
	[ -s "$LEOBJ/libedit.a" ] || {
		echo "libedit.a is 0 bytes -- that is the old stub defect" >&2
		exit 1
	}
	echo "built $LEOBJ/libedit.a ($(stat -f %z "$LEOBJ/libedit.a") bytes)"
}

build_libedit_host() {
	echo "==> libedit (Darwin host archive, for running the shell here)"
	rm -rf "$LEHOST"; mkdir -p "$LEHOST"
	gen_libedit_headers "$LEHOST/gen"
	# termcap.o goes in its own directory, NOT in $LEHOST: the archive is
	# built from "$LEHOST"/*.o, and this object must stay a separate,
	# separately-identified link input so that `nm $HOSTDIR/sh' shows where
	# the six symbols came from.
	rm -rf "$LEHOME"; mkdir -p "$LEHOME"
	build_termcap_host
	local d="$R/BSD/lib/libedit/src"
	# SRCS mirrors BSD/lib/libedit/Makefile: the six replacement sources
	# (vis unvis getline wcsdup strlcpy strlcat) are omitted because
	# config.h says the platform already provides them, exactly as that
	# Makefile now gates them.
	local f
	for f in chared chartype common el eln emacs filecomplete hist history \
		historyn keymacro literal map parse prompt read readline \
		reallocarr refresh search sig terminal tokenizer tokenizern tty vi; do
		# shellcheck disable=SC2086
		# -I"$L/libsystem_termcap" so terminal.c's `#include <termcap.h>'
		# reaches THIS component's header and not the host's. See
		# build_termcap_host.
		$HOST_CC -c -arch x86_64 -I "$d" -I "$R/BSD/lib/libedit" \
			-I "$L/libsystem_termcap" \
			-I "$LEHOST/gen" -o "$LEHOST/$f.o" "$d/$f.c" \
			|| { echo "libedit host build FAILED on $f.c" >&2; exit 1; }
	done
	rm -f "$LEHOST/libedit.a"
	ar rcs "$LEHOST/libedit.a" "$LEHOST"/*.o
	[ -s "$LEHOST/libedit.a" ] || {
		echo "host libedit.a is 0 bytes" >&2; exit 1; }
	echo "built $LEHOST/libedit.a ($(stat -f %z "$LEHOST/libedit.a") bytes)"
}

build_host() {
	local srcs="$SRCS" b src
	build_libedit
	mkdir -p "$HOSTDIR"
	echo "==> host build (runnable verification binary)"
	for s in $srcs; do
		b=$(basename "$s" .c)
		src=$(src_for "$s")
		# shellcheck disable=SC2086
		$HOST_CC -c -arch x86_64 $COMMON_CFLAGS \
			-I"$S" -I"$GENDIR" -I"$S/bltin" -I"$LEDIR" \
			-o "$HOSTDIR/$b.o" "$src"
	done
	# -ledit is $LEHOST/libedit.a (see build_libedit_host). The termcap it
	# needs -- tgetent/tgetflag/tgetnum/tgetstr/tgoto/tputs, which
	# terminal.c calls unconditionally from terminal_set() -- is
	# $LEHOST/termcap.o, built by build_termcap_host from
	# Libraries/Libsystem/libsystem_termcap/termcap.c. Not the host's
	# libncurses termcap: see the note on build_termcap_host for why that
	# matters to what the host pty test actually proves.
	$HOST_CC -arch x86_64 -o "$HOSTDIR/sh" "$HOSTDIR"/*.o \
		"$LEHOME/termcap.o" -L"$LEHOST" -ledit
	echo "built $HOSTDIR/sh"
	echo "  the six termcap symbols resolve to libsystem_termcap, not to libncurses:"
	nm "$HOSTDIR/sh" | grep -E ' T _(tgetent|tgetflag|tgetnum|tgetstr|tgoto|tputs)$' |
	    sed 's/^/    /'
}

TERM_CAP_SRC=$L/libsystem_termcap/termcap.c
LEHOME=${LEHOME:-/tmp/ravyn-termcap-host}

# The host shell links THIS component's termcap.c, not the host's libncurses
# termcap. Two reasons, and the second is the important one:
#
#   1. libedit's terminal.c calls the six entry points unconditionally, so
#      something has to define them either way, and it should be the same code
#      the ravynOS target gets.
#   2. It makes the host pty test (tools/bootlab/pty-lineedit-test.py) an
#      end-to-end RUNTIME test of this component rather than of the host's
#      ncurses. The same negative control that scores 3/10 with -DNO_HISTORY
#      scores 10/10 here only if tgetent, tgetstr, tgoto and tputs actually
#      work; a broken entry table would take it back down.
#
# -I points at the component so terminal.c's `#include <termcap.h>' (it is
# reached, because libedit's src/sys.h pulls in config.h and config.h has
# HAVE_TERMCAP_H 1) resolves to THIS header and not to the host's.
build_termcap_host() {
	$HOST_CC -c -arch x86_64 -Wall -Wextra -Wno-unused-parameter \
		-I"$L/libsystem_termcap" -o "$LEHOME/termcap.o" "$TERM_CAP_SRC" \
		|| { echo "termcap host build FAILED" >&2; exit 1; }
}

# --------------------------------------------------------------------------
# libsystem_termcap, static archive.
#
# libedit's terminal.c needs tgetent/tgetflag/tgetnum/tgetstr/tgoto/tputs and
# ravynOS had none of them. Libraries/Libsystem/libsystem_termcap is an
# original 4-clause BSD implementation of the six entry points; this builds its
# static/ subdir, which is the only product the target link consumes.
#
# The archive also installs <termcap.h> into $SDK/usr/include, which is the
# part that is easy to overlook: libedit's src/sys.h includes config.h into
# every translation unit and config.h has HAVE_TERMCAP_H 1, so src/terminal.c
# does `#include <termcap.h>' and fails without it -- and, worse, would take an
# implicit `int tgetstr()' (truncating the returned pointer to 32 bits) if the
# prototypes were declared some other way.
#
# Same bmake environment as build_libedit_target; see the comment there for
# why each of those values is what it is.
build_termcap_static() {
	echo "==> libsystem_termcap (ravynOS static archive)"
	(
		cd "$L/libsystem_termcap/static" || exit 1
		RAVYN_SDKROOT="$SDK" SYSROOT_DIR="$SDK" \
		ROOT_SOURCE_DIR="$R" \
		CpuArch=x86_64 MACOS_VERSION_MIN="${MACOS_VERSION_MIN:-15.0}" \
		CC="$R/tools/bootlab/isysroot-cc" \
		AR="$R/tools/bootlab/macar" \
		LD=ld \
		EXTRA_DEFINES="-DXNU_PLATFORM_MacOSX" \
		"$BMAKE" -m "$R/BSD/share/mk" all
	) || { echo "libsystem_termcap build FAILED" >&2; exit 1; }
	[ -s "$L/libsystem_termcap/static/libsystem_termcap_static.a" ] || {
		echo "libsystem_termcap_static.a is 0 bytes" >&2; exit 1; }
	[ -s "$SDK/usr/include/termcap.h" ] || {
		echo "termcap.h was not installed into the SDK" >&2; exit 1; }
	echo "built $L/libsystem_termcap/static/libsystem_termcap_static.a"
	echo "  ($(stat -f %z "$L/libsystem_termcap/static/libsystem_termcap_static.a") bytes)"
}

build_target() {
	local s b
	echo "==> ravynOS static build"
	mkdir -p "$OBJDIR"
	# link-static.sh owns the archive list, the residue stubs and the
	# -DVARIANT_STATIC pthread archive, and it verifies the shape of what it
	# produces (NOUNDEFS / 0 LC_LOAD_DYLIB / LC_UNIXTHREAD) and fails if the
	# shape is wrong. Everything it needs beyond its own defaults is passed
	# through RAVYN_EXTRA_CFLAGS / RAVYN_EXTRA_INCLUDES / RAVYN_EXTRA_LIBS.
	#
	# SHELL_TARGET_NO_HISTORY defaults to 0: the target now builds WITH line
	# editing, because libsystem_termcap supplies the six termcap entry points
	# libedit's terminal.c calls unconditionally. Set it back to 1 for the
	# no-editing configuration, which is still a complete shell -- the nine
	# NO_HISTORY guards (eval.c, input.c, var.c, var.h, parser.c, main.c,
	# trap.c, options.c, histedit.c) take the feature off coherently rather
	# than half-on.
	if [ "${SHELL_TARGET_NO_HISTORY:-0}" = "1" ]; then
		echo "==> target: -DNO_HISTORY, no libedit, no line editing"
		export RAVYN_EXTRA_CFLAGS="$COMMON_CFLAGS -DNO_HISTORY"
		# $LEDIR (libedit's headers) is deliberately absent: with the
		# feature off nothing includes histedit.h, and pointing at it
		# would only invite an accidental dependency.
		export RAVYN_EXTRA_INCLUDES="-isystem $SDK/usr/include -isystem $S -isystem $GENDIR"
		# passwd/group database resolves what expand.c's `~user' and
		# parser.c's getpwlogin()/getusername() need.
		export RAVYN_EXTRA_LIBS="-L$L/libsystem_pwdgrp/static -lsystem_pwdgrp_static"
	else
		build_termcap_static
		build_libedit_target
		export RAVYN_EXTRA_CFLAGS="$COMMON_CFLAGS"
		export RAVYN_EXTRA_INCLUDES="-isystem $SDK/usr/include -isystem $S -isystem $GENDIR -isystem $LEDIR"
		# -ledit is first so the built-in archives win anything both define;
		# the passwd/group database follows and resolves what they leave
		# undefined. expand.c's `~user' and parser.c's getpwlogin()/
		# getusername() need getpwnam/getpwuid, and libedit's
		# filecomplete.c needs the _r forms.
		#
		# termcap comes LAST on purpose. libedit.a references
		# tgetent/tgetflag/tgetnum/tgetstr/tgoto/tputs, and this is the
		# only archive in the ravynOS tree that defines them, so if a
		# future archive ever grows a second definition this order
		# decides which one wins instead of leaving it to chance.
		#
		# -lcorecrypto is what HISTORY costs, and only history. libedit
		# saves its history file through mkstemp --
		# BSD/lib/libedit/src/readline.c:1304 and src/vi.c:1020 -- and
		# libc.a's mkstemp member calls _arc4random_uniform, whose own
		# member (arc4random.o) then needs _ccrng and _ccrng_uniform
		# from CommonCrypto. _ccrng is defined in exactly one archive in
		# this tree, libcorecrypto.a, and it is not on link-static.sh's
		# LIBS line. With -DNO_HISTORY this archive is never reached,
		# which is why the shell linked for so long without it.
		#
		# It goes here, in this program's RAVYN_EXTRA_LIBS, rather than
		# into link-static.sh's LIBS: the passthrough is documented as
		# the way a program names an archive it needs, and mkstemp is a
		# dependency of libedit's history writer, not of every static
		# ravynOS program.
		export RAVYN_EXTRA_LIBS="-L$LEOBJ -ledit \
			-L$L/libsystem_pwdgrp/static -lsystem_pwdgrp_static \
			-L$L/libsystem_termcap/static -lsystem_termcap_static \
			-L$L/corecrypto -lcorecrypto"
	fi
	# shellcheck disable=SC2086
	"$LINK_STATIC" -o "$OBJDIR/sh" \
		"$STATIC_START" \
		"$S/ravynos_port.c" \
		$(for s in $SRCS; do src_for "$s"; done) \
		|| { echo "static link FAILED" >&2; exit 1; }
	echo "built $OBJDIR/sh"
}

