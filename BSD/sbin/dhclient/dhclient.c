#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <unistd.h>
#include <sys/types.h>
#include <sys/socket.h>
#include <sys/ioctl.h>
#include <net/if.h>
#include <netinet/in.h>
#include <arpa/inet.h>
#include <errno.h>

int main(int argc, char *argv[]) {
    const char *ifname = (argc > 1) ? argv[1] : "en0";
    printf("[dhclient] configuring interface %s...\n", ifname);

    int s = socket(AF_INET, SOCK_DGRAM, 0);
    if (s < 0) {
        perror("socket");
        return 1;
    }

    struct ifreq ifr;
    memset(&ifr, 0, sizeof(ifr));
    strncpy(ifr.ifr_name, ifname, IFNAMSIZ - 1);

    // Bring interface up
    if (ioctl(s, SIOCGIFFLAGS, &ifr) == 0) {
        ifr.ifr_flags |= IFF_UP | IFF_RUNNING;
        ioctl(s, SIOCSIFFLAGS, &ifr);
    }

    // Set IP address (10.0.2.15 for QEMU SLIRP)
    struct sockaddr_in *sin = (struct sockaddr_in *)&ifr.ifr_addr;
    sin->sin_family = AF_INET;
    sin->sin_len = sizeof(struct sockaddr_in);
    inet_pton(AF_INET, "10.0.2.15", &sin->sin_addr);
    if (ioctl(s, SIOCSIFADDR, &ifr) < 0) {
        perror("SIOCSIFADDR");
    }

    // Set netmask (255.255.255.0)
    inet_pton(AF_INET, "255.255.255.0", &sin->sin_addr);
    if (ioctl(s, SIOCSIFNETMASK, &ifr) < 0) {
        perror("SIOCSIFNETMASK");
    }

    close(s);

    // Write /etc/resolv.conf
    FILE *f = fopen("/etc/resolv.conf", "w");
    if (f) {
        fprintf(f, "# Generated by dhclient\n");
        fprintf(f, "nameserver 10.0.2.3\n");
        fprintf(f, "nameserver 1.1.1.1\n");
        fclose(f);
        printf("[dhclient] updated /etc/resolv.conf\n");
    }

    printf("[dhclient] %s configured with 10.0.2.15 netmask 255.255.255.0\n", ifname);
    return 0;
}
